export type MiniGameType = 'chronology' | 'matching' | 'odd-one-out' | 'fill-blanks' | 'true-false';

export interface MiniGameBase {
  id: string;
  type: MiniGameType;
  title: string;
  description: string;
  afterChapter: number;
}

export interface ChronologyItem {
  id: string;
  text: string;
  year: number;
}

export interface ChronologyGame extends MiniGameBase {
  type: 'chronology';
  items: ChronologyItem[];
  successFeedback: string;
  failFeedback: string;
}

export interface MatchingPair {
  id: string;
  term: string;
  definition: string;
}

export interface MatchingGame extends MiniGameBase {
  type: 'matching';
  pairs: MatchingPair[];
  successFeedback: string;
  failFeedback: string;
}

export interface OddOneOutOption {
  id: string;
  text: string;
  isOdd: boolean;
  explanation: string;
}

export interface OddOneOutGame extends MiniGameBase {
  type: 'odd-one-out';
  question: string;
  options: OddOneOutOption[];
  successFeedback: string;
  failFeedback: string;
}

export interface FillBlankItem {
  id: string;
  sentence: string; // with ___ as blank
  answer: string;
  hint: string;
  options: string[]; // multiple choice
}

export interface FillBlanksGame extends MiniGameBase {
  type: 'fill-blanks';
  items: FillBlankItem[];
  successFeedback: string;
  failFeedback: string;
}

export interface TrueFalseItem {
  id: string;
  statement: string;
  isTrue: boolean;
  explanation: string;
}

export interface TrueFalseGame extends MiniGameBase {
  type: 'true-false';
  items: TrueFalseItem[];
  successFeedback: string;
  failFeedback: string;
}

